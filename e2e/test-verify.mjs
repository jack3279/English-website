import { chromium } from '@playwright/test';
const browser = await chromium.launch();
const page = await browser.newPage();
page.on('console', (m) => console.log('  [console]', m.text()));
page.on('pageerror', (e) => console.log('  [pageerror]', e.message));
await page.goto('https://17say.org/login');
await page.fill('input[type="email"]', 'admin@17say.org');
await page.fill('input[type="password"]', 'Demo1234!');
await page.click('button[type="submit"]');
await page.waitForURL(/\/admin\b/);
await page.goto('https://17say.org/students');
await page.waitForLoadState('networkidle');
await page.waitForTimeout(800);
const unique = `toast-debug-${Date.now()}`;
await page.locator('button:has-text("新建学员")').first().click();
await page.fill('input#student-name', unique);
await page.locator('button:has-text("保存")').first().click();
await page.waitForTimeout(1500);
const toastCount = await page.locator('[role="status"]').count();
const toastText = await page.locator('[role="status"]').allTextContents();
console.log('toast count:', toastCount, 'text:', JSON.stringify(toastText));
const portalHtml = await page.evaluate(() => document.querySelector('.pointer-events-none.fixed.top-4')?.outerHTML?.slice(0, 400) || 'no portal');
console.log('portal HTML:', portalHtml);
await page.screenshot({ path: 'e2e/test-results/toast-debug.png' });
await browser.close();